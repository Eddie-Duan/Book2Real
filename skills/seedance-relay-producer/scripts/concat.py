#!/usr/bin/env python3
"""
Step 6A: 音画轨归一化与接力成片拼接。
- 统一所有 PASS 片段为 24fps、yuv420p、48kHz 标准静音轨，杜绝音轨缺失导致的拼接崩溃
- Level A (双锚定) 与 Level C (硬切) 直接零转场首尾拼接
- Level B (降级软转场) 使用 ffmpeg xfade=fade 插入 0.4s 交叉溶解
- 生成 out/concat.txt 与 out/final_movie.mp4
"""
import argparse
import json
import subprocess
import sys
from pathlib import Path
from typing import Any, Dict, List

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from scripts.common import append_run_log, load_config, load_pipeline_state, run_ffprobe_info


def normalize_clip_for_concat(
    src_clip: Path, norm_clip: Path, width: int, height: int, fps: int = 24, sample_rate: int = 48000
) -> float:
    """将单段视频转码为一致的帧率、像素格式并补齐标准静音音轨，返回实际时长。"""
    norm_clip.parent.mkdir(parents=True, exist_ok=True)
    cmd = [
        "ffmpeg",
        "-y",
        "-i",
        str(src_clip),
        "-f",
        "lavfi",
        "-i",
        f"anullsrc=channel_layout=stereo:sample_rate={sample_rate}",
        "-vf",
        f"scale={width}:{height}:flags=lanczos,fps={fps},format=yuv420p",
        "-c:v",
        "libx264",
        "-crf",
        "18",
        "-preset",
        "medium",
        "-c:a",
        "aac",
        "-b:a",
        "128k",
        "-shortest",
        str(norm_clip),
    ]
    proc = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8", errors="replace", check=False)
    if proc.returncode != 0:
        raise RuntimeError(f"Normalize clip failed for {src_clip}: {proc.stderr}")

    probe = run_ffprobe_info(norm_clip)
    return float(probe["format"]["duration"])


def probe_movie(path: Path) -> Dict[str, Any]:
    """成片规格：分辨率/帧率/时长/是否有音轨。官方要求 ≥720P、≥24fps。"""
    probe = run_ffprobe_info(path)
    info: Dict[str, Any] = {"duration": None, "fps": None, "width": None, "height": None,
                            "has_audio": False, "audio_codec": None}
    try:
        info["duration"] = round(float(probe["format"]["duration"]), 3)
    except Exception:
        pass
    for s in probe.get("streams", []):
        if s.get("codec_type") == "video" and info["fps"] is None:
            info["width"] = int(s.get("width") or 0)
            info["height"] = int(s.get("height") or 0)
            num, _, den = str(s.get("r_frame_rate") or "0/1").partition("/")
            try:
                info["fps"] = round(float(num) / float(den or 1), 3)
            except Exception:
                pass
        elif s.get("codec_type") == "audio":
            info["has_audio"] = True
            info["audio_codec"] = s.get("codec_name")
    return info


def audio_level(path: Path) -> Dict[str, Any]:
    """实测响度（dB）。anullsrc 静音轨是 -91 dB，用来卡住"旁白没铺进去"。"""
    cmd = ["ffmpeg", "-hide_banner", "-i", str(path), "-af", "volumedetect", "-f", "null", "-"]
    proc = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8", errors="replace", check=False)
    out = {"mean_volume_db": None, "max_volume_db": None}
    for line in (proc.stderr or "").splitlines():
        for key, field in (("mean_volume:", "mean_volume_db"), ("max_volume:", "max_volume_db")):
            if key in line:
                try:
                    out[field] = float(line.split(key, 1)[1].strip().split(" ")[0])
                except Exception:
                    pass
    return out


def mux_audio(video: Path, audio: Path, out: Path, sample_rate: int) -> None:
    """把旁白轨铺到已拼好的画面上；不重编码视频。"""
    cmd = [
        "ffmpeg", "-y", "-i", str(video), "-i", str(audio),
        "-map", "0:v:0", "-map", "1:a:0", "-c:v", "copy",
        "-c:a", "aac", "-b:a", "160k", "-ar", str(sample_rate),
        "-shortest", "-metadata", "comment=Generated by Seedance AI Pipeline",
        str(out),
    ]
    proc = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8", errors="replace", check=False)
    if proc.returncode != 0:
        raise RuntimeError(f"Mux narration failed: {proc.stderr}")


def build_final_movie(out_dir: Path, cfg: Dict[str, Any], audio: Path | None = None) -> Dict[str, Any]:
    state = load_pipeline_state(out_dir)
    fps = int(cfg["runtime"]["target_fps"])
    sr = int(cfg["runtime"]["audio_sample_rate"])

    ordered_pages = sorted(state["pages"].values(), key=lambda x: x.get("preflight", {}).get("page_index", 0))
    pass_pages = [p for p in ordered_pages if p["status"] == "PASS"]

    if not pass_pages:
        raise RuntimeError("没有状态为 PASS 的页面可供拼接。")

    # 以首张合格页作为全局基准分辨率；若该段成片比页图大（720p/1080p 生成），
    # 用成片分辨率，避免把 1112x834 的片段压回 640x480 白白损失清晰度。
    base_w = pass_pages[0]["preflight"]["width"]
    base_h = pass_pages[0]["preflight"]["height"]
    first_clip = out_dir / pass_pages[0]["page_id"] / "clip.mp4"
    if first_clip.exists():
        probe = run_ffprobe_info(first_clip)
        for s in probe.get("streams", []):
            if s.get("codec_type") == "video":
                cw, ch = int(s["width"]), int(s["height"])
                if cw * ch > base_w * base_h:
                    base_w, base_h = cw, ch
                break

    norm_dir = out_dir / "_normalized_clips"
    norm_entries: List[Dict[str, Any]] = []
    concat_lines: List[str] = []

    for p in pass_pages:
        pid = p["page_id"]
        src_clip = out_dir / pid / "clip.mp4"
        norm_clip = norm_dir / f"{pid}_norm.mp4"
        dur = normalize_clip_for_concat(src_clip, norm_clip, base_w, base_h, fps=fps, sample_rate=sr)
        plan = p["preflight"]["generation_plan"]
        norm_entries.append(
            {
                "page_id": pid,
                "path": norm_clip,
                "duration": dur,
                "transition_after": plan.get("transition_after"),
                "transition_sec": float(plan.get("transition_sec") or 0.0),
            }
        )
        concat_lines.append(f"file '{norm_clip.resolve().as_posix()}'")

    concat_txt = out_dir / "concat.txt"
    concat_txt.write_text("\n".join(concat_lines) + "\n", encoding="utf-8")

    final_movie = out_dir / "final_movie.mp4"
    # 有旁白轨时先拼视频（-an），再单独铺音轨，避免 xfade/静音轨把旁白挤掉
    video_target = (out_dir / "_final_movie_video.mp4") if audio else final_movie
    has_xfade = any(e["transition_after"] and e["transition_sec"] > 0 for e in norm_entries[:-1])

    if len(norm_entries) == 1 or not has_xfade:
        cmd = [
            "ffmpeg",
            "-y",
            "-f",
            "concat",
            "-safe",
            "0",
            "-i",
            str(concat_txt),
            "-c",
            "copy",
            "-metadata",
            "comment=Generated by Seedance AI Pipeline",
        ]
        if audio:
            cmd.append("-an")
        cmd.append(str(video_target))
    else:
        # 构造带 Level B xfade 交叉溶解的复杂滤镜图
        inputs = []
        for e in norm_entries:
            inputs.extend(["-i", str(e["path"])])

        v_filters = []
        a_filters = []
        curr_v = "[0:v]"
        curr_a = "[0:a]"
        offset = norm_entries[0]["duration"]

        for idx in range(len(norm_entries) - 1):
            next_v = f"[{idx + 1}:v]"
            next_a = f"[{idx + 1}:a]"
            out_v = f"[v{idx + 1}]"
            out_a = f"[a{idx + 1}]"
            t_sec = norm_entries[idx]["transition_sec"] if norm_entries[idx]["transition_after"] else 0.001
            t_type = norm_entries[idx]["transition_after"] or "fade"
            offset = max(offset - t_sec, 0.0)

            v_filters.append(f"{curr_v}{next_v}xfade=transition={t_type}:duration={t_sec:.3f}:offset={offset:.3f}{out_v}")
            a_filters.append(f"{curr_a}{next_a}acrossfade=d={t_sec:.3f}{out_a}")

            curr_v = out_v
            curr_a = out_a
            offset += norm_entries[idx + 1]["duration"]

        filter_complex = ";".join(v_filters + a_filters)
        cmd = [
            "ffmpeg",
            "-y",
            *inputs,
            "-filter_complex",
            filter_complex,
            "-map",
            curr_v,
        ]
        if audio:
            cmd.append("-an")  # 旁白在拼接之后单独铺
        else:
            cmd.extend(["-map", curr_a, "-c:a", "aac"])
        cmd.extend([
            "-c:v",
            "libx264",
            "-crf",
            "18",
            "-pix_fmt",
            "yuv420p",
            "-metadata",
            "comment=Generated by Seedance AI Pipeline",
            str(video_target),
        ])

    proc = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8", errors="replace", check=False)
    if proc.returncode != 0:
        raise RuntimeError(f"Final concat failed: {proc.stderr}")

    # 事后校验：成片每条接缝实际用了什么转场、硬切占多少，写盘留痕。
    # 全片纯硬切通常意味着分镜/桥接没生效（或 S2 没跑），需要人工回看，不能静默交付。
    seam_audit = []
    for idx, entry in enumerate(norm_entries[:-1]):
        transition = entry["transition_after"]
        sec = entry["transition_sec"] if transition else 0.0
        seam_audit.append(
            {
                "after_page": entry["page_id"],
                "next_page": norm_entries[idx + 1]["page_id"],
                "transition": transition or "hard_cut",
                "transition_sec": round(float(sec), 3),
            }
        )
    hard_cut_count = sum(1 for s in seam_audit if s["transition"] == "hard_cut")
    # 分镜侧有效的转场不只 xfade：SHARED_T 桥接帧与 POST 交叉溶解在画面上也是转场。
    # 只有"计划里根本没安排转场"的全硬切才算失败；计划路径取自 state.meta.plan_path。
    planned_effective = 0
    planned_total = 0
    plan_path = str((state.get("meta") or {}).get("plan_path") or "")
    if plan_path and Path(plan_path).is_file():
        try:
            plan_json = json.loads(Path(plan_path).read_text(encoding="utf-8-sig"))
            seams = plan_json.get("seams") or []
            planned_total = 0
            for s in seams:
                if str(s.get("from_segment") or "").split(" ")[0] == str(s.get("to_segment") or "").split(" ")[0]:
                    continue  # 段内合并页之间没有拼接接缝，不计入成片转场审计
                planned_total += 1
                decision = str(s.get("decision") or "")
                cut = str(s.get("cut") or "")
                # CONTINUOUS 走双锚定、DESIGNED_TRANSITION 走共享桥接帧/T；它们都不是裸硬切。
                if decision in {"CONTINUOUS", "DESIGNED_TRANSITION"} or cut == "xfade":
                    planned_effective += 1
        except Exception:  # noqa: BLE001 - 审计读不到计划时不阻断成片
            planned_effective, planned_total = 0, 0
    concat_audit = {
        "seams": seam_audit,
        "hard_cut_count": hard_cut_count,
        "xfade_count": len(seam_audit) - hard_cut_count,
        "hard_cut_ratio": round(hard_cut_count / max(1, len(seam_audit)), 3),
        "plan_seams_total": planned_total,
        "plan_effective_transitions": planned_effective,
        "transition_audit_ok": bool(
            len(seam_audit) <= 1
            or hard_cut_count < len(seam_audit)
            or (planned_total > 0 and planned_effective > 0)
        ),
        "warning": (
            "全部接缝都是硬切：请确认 scene_plan 的 SHARED_T/POST 转场已生效，"
            "否则成片只会有'简单切换'"
            if seam_audit and hard_cut_count == len(seam_audit)
            else None
        ),
    }
    (out_dir / "concat_audit.json").write_text(
        json.dumps(concat_audit, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    if concat_audit["warning"]:
        print(f"[WARN] {concat_audit['warning']}")

    if audio:
        mux_audio(video_target, audio, final_movie, sr)
        video_target.unlink(missing_ok=True)

    info = probe_movie(final_movie)
    level = audio_level(final_movie)
    summary = {
        "final_movie": str(final_movie),
        "concat_list": str(concat_txt),
        "included_pages": [e["page_id"] for e in norm_entries],
        "used_xfade_filter": has_xfade,
        "concat_audit": str(out_dir / "concat_audit.json"),
        "hard_cut_ratio": concat_audit["hard_cut_ratio"],
        "ai_disclosure_metadata": "Generated by Seedance AI Pipeline",
        "narration": str(audio) if audio else None,
        "spec": info,
        "audio_level": level,
        "spec_ok": {
            "min_720p": bool(info.get("width") and info.get("height")
                             and min(info["width"], info["height"]) >= 720),
            "min_24fps": bool(info.get("fps") and info["fps"] >= 24),
            "in_100_180s": bool(info.get("duration") and 100 <= info["duration"] <= 180),
            "audio_not_silent": bool(level.get("max_volume_db") is not None
                                     and level["max_volume_db"] > -20.0),
        },
    }
    (out_dir / "final_movie.json").write_text(
        json.dumps(summary, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    append_run_log(out_dir, "movie_concatenated", summary)
    print(f"[CONCAT] 成片生成成功: {final_movie} (共拼接 {len(norm_entries)} 页)")
    print(f"[CONCAT] 规格 {info}  响度 {level}  自检 {summary['spec_ok']}")
    return summary


def main() -> None:
    parser = argparse.ArgumentParser(description="Concatenate QC-passed video clips into final movie")
    parser.add_argument("--out-dir", type=Path, default=Path("out"), help="Workspace output directory")
    parser.add_argument("--config", type=Path, default=None, help="Path to config.yaml")
    parser.add_argument("--audio", type=Path, default=None,
                        help="旁白轨（build_narration.py 出的 mp3）；不给则塞标准静音轨")
    args = parser.parse_args()

    cfg = load_config(args.config)
    build_final_movie(args.out_dir, cfg, audio=args.audio)


if __name__ == "__main__":
    main()
